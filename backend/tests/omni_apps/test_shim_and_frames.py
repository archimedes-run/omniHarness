"""The platform shim the gateway injects, and the frame-markup scan (Spec 011 FR-018, FR-028). Pure.

The shim is the guard the worker cannot touch: it comes from the gateway's own
copy, runs first, and any shim the bundle carries is dropped. The scan is
defence in depth (a name built from strings at run time dodges it; Trusted
Types in the CSP and the shim are what stop that).
"""

from __future__ import annotations

import base64
import hashlib
from pathlib import Path

import pytest

from app.gateway.apps import bundle

REPO = Path(__file__).resolve().parents[3]
FRONTEND_SHIM = REPO / "frontend" / "src" / "core" / "apps" / "shim" / "omni-shim.js"


def _sha(text: str) -> str:
    return base64.b64encode(hashlib.sha256(text.encode()).digest()).decode()


def test_the_gateway_shim_is_the_generated_file() -> None:
    if not FRONTEND_SHIM.exists():
        pytest.skip("the generated shim is not in this checkout yet (host page PR)")
    assert bundle.SHIM_FILE.read_bytes() == FRONTEND_SHIM.read_bytes(), "copy frontend/src/core/apps/shim/omni-shim.js to backend/app/gateway/apps/kit/"


def test_the_shim_is_present_and_names_what_it_removes() -> None:
    text = bundle.shim()
    assert text.startswith("/* GENERATED by scripts/build-app-shim.mjs") and "RTCPeerConnection" in text and "</script" not in text


def test_the_shim_is_injected_first_and_hashed_first() -> None:
    html, hashes = bundle.inline({"index.html": b"<!doctype html><html><head><title>x</title></head><body><script>var a=1;</script></body></html>"})
    text = html.decode()
    assert text.startswith("<!doctype html><html><head><script>" + bundle.shim() + "</script>"), "after the doctype, before every script"
    assert hashes == [_sha(bundle.shim()), _sha("var a=1;")]


def test_a_script_before_head_still_comes_after_the_shim() -> None:
    html, _ = bundle.inline({"index.html": b"<html><script>var early=1;</script><head></head></html>"})
    text = html.decode()
    assert text.index(bundle.shim()) < text.index("var early=1;")


@pytest.mark.parametrize(
    "worker_shim",
    [
        b'<script src="omni-shim.js"></script>',
        b'<script src="./kit/omni-shim.js?v=2"></script>',
        b"<script>" + bundle.SHIM_FILE.read_bytes() + b"</script>",
        b"<script>/* GENERATED by scripts/build-app-shim.mjs ALTERED */ window.omni = {evil: true};</script>",
    ],
)
def test_a_shim_in_the_bundle_is_dropped_and_replaced(worker_shim) -> None:
    files = {
        "index.html": b"<html><head>" + worker_shim + b"</head><body><script>var app=1;</script></body></html>",
        "omni-shim.js": b"window.omni={evil:true}",
        "kit/omni-shim.js": b"window.omni={evil:true}",
    }
    html, hashes = bundle.inline(files)
    text = html.decode()
    assert "evil" not in text and "ALTERED" not in text
    assert text.count("/* GENERATED by scripts/build-app-shim.mjs") == 1
    assert hashes == [_sha(bundle.shim()), _sha("var app=1;")]


def test_a_bundle_without_head_or_scripts_still_gets_the_shim() -> None:
    html, hashes = bundle.inline({"index.html": b"<!doctype html><p>hi</p>"})
    assert html.decode().startswith("<!doctype html><script>") and len(hashes) == 1


@pytest.mark.parametrize(
    "html",
    [
        b"<iframe src='data:text/html,x'></iframe>",
        b"<IFRAME>",
        b"<frame>",
        b"<frameset></frameset>",
        b"<object data='x'></object>",
        b"<embed src='x'>",
        b"<portal src='x'></portal>",
        b"<fencedframe></fencedframe>",
        b"<div srcdoc='x'></div>",
        b"<script>el.srcdoc = 'x';</script>",
        b"<script>el.setAttribute('srcdoc', 'x');</script>",
        b"<script>const t = '<iframe>';</script>",
    ],
)
def test_frame_markup_is_refused(html) -> None:
    with pytest.raises(bundle.BundleError) as err:
        bundle.inline({"index.html": html})
    assert err.value.code == "forbidden_markup"


def test_ordinary_code_mentioning_frames_by_word_passes() -> None:
    bundle.inline({"index.html": b"<script>const frameCount = 3; const objectives = {}; // embedded</script>"})
