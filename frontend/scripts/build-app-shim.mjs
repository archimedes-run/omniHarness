#!/usr/bin/env node
/**
 * Spec 011: build the platform shim (src/core/apps/shim/omni-shim.js), the one
 * file the app kit copies into every app, from its source and the two files
 * the host page validates with: protocol.schema.json and validate.js. Host and
 * shim therefore check messages with the same schema and the same function.
 *
 *   node scripts/build-app-shim.mjs          write omni-shim.js
 *   node scripts/build-app-shim.mjs --check  exit 1 if it is out of date
 *
 * tests/unit/apps-shim.test.ts runs the same build and fails on drift.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const apps = join(here, "..", "src", "core", "apps");

export function buildShim() {
  const source = readFileSync(join(apps, "shim", "omni-shim.src.js"), "utf8");
  const schema = JSON.parse(
    readFileSync(join(apps, "protocol.schema.json"), "utf8"),
  );
  delete schema.$comment;
  const validate = readFileSync(join(apps, "validate.js"), "utf8");
  const start = validate.indexOf("export function validateProtocolMessage");
  if (start === -1) throw new Error("validate.js: function not found");
  const fn = validate.slice(start + "export ".length).trim();
  const schemaMarker = "/*@@PROTOCOL_SCHEMA@@*/ null";
  const validateMarker = "/*@@VALIDATE@@*/ null";
  if (!source.includes(schemaMarker) || !source.includes(validateMarker)) {
    throw new Error("omni-shim.src.js: a marker is missing");
  }
  const header =
    "/* GENERATED by scripts/build-app-shim.mjs from omni-shim.src.js, " +
    "protocol.schema.json and validate.js. Do not edit. */\n";
  return (
    header +
    source
      .replace(schemaMarker, () => JSON.stringify(schema))
      .replace(validateMarker, () => `(${fn})`)
  );
}

const out = join(apps, "shim", "omni-shim.js");
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const built = buildShim();
  if (process.argv.includes("--check")) {
    const current = readFileSync(out, "utf8");
    if (current !== built) {
      console.error(
        "omni-shim.js is out of date: run node scripts/build-app-shim.mjs",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(out, built);
    console.log(`wrote ${out}`);
  }
}
